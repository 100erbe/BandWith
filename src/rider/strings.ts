export const RIDER_STRINGS: Record<RiderLang, RiderStrings> = { en, it, es, fr, de, pt };

export function pickRiderLang(preferred: readonly string[]): RiderLang {
  for (const raw of preferred) {
    const code = raw.slice(0, 2).toLowerCase();
    if (code in RIDER_STRINGS) return code as RiderLang;
  }
  return 'en';
}

export function fill(template: string, vars: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? vars[k] : m));
}
